/**
 * Get overdue vaccinations for a pet
 * @param {Object} pet - Pet object
 * @param {Array} existingVaccinations - Array of existing vaccination records
 * @returns {Array} Array of overdue vaccinations
 */
export function getOverdueVaccinations(pet, existingVaccinations = []) {
  const upcomingVaccinations = generateVaccinationAppointments(pet, existingVaccinations)
  const now = new Date()
  
  return upcomingVaccinations.filter(vaccination => {
    const dueDate = new Date(vaccination.suggestedDate)
    return dueDate < now
  })
}

/**
 * Get vaccination schedule summary for a pet
 * @param {Object} pet - Pet object
 * @param {Array} existingVaccinations - Array of existing vaccination records
 * @returns {Object} Vaccination schedule summary
 */
export function getVaccinationScheduleSummary(pet, existingVaccinations = []) {
  const upcomingVaccinations = generateVaccinationAppointments(pet, existingVaccinations)
  const overdueVaccinations = getOverdueVaccinations(pet, existingVaccinations)
  
  const completedVaccinations = existingVaccinations.filter(v => v.completed)
  const pendingVaccinations = upcomingVaccinations.filter(v => !v.completed)
  
  return {
    total: existingVaccinations.length + upcomingVaccinations.length,
    completed: completedVaccinations.length,
    pending: pendingVaccinations.length,
    overdue: overdueVaccinations.length,
    nextDue: upcomingVaccinations.length > 0 ? upcomingVaccinations[0] : null,
    series: upcomingVaccinations.length > 0 ? upcomingVaccinations[0].series : null,
    progress: existingVaccinations.length > 0 ? 
      Math.round((completedVaccinations.length / existingVaccinations.length) * 100) : 0
  }
}

