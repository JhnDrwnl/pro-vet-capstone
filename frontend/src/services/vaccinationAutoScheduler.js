/**
 * Automatically schedule next vaccination appointments for a pet
 * @param {Object} pet - Pet object
 * @param {Array} existingVaccinations - Array of existing vaccination records
 * @param {Object} user - User object (owner)
 * @returns {Promise<Array>} Array of created appointment suggestions
 */
export async function autoScheduleVaccinations(pet, existingVaccinations = [], user = null) {
  try {
    console.log('🔄 Starting auto-scheduling for pet:', pet.name, 'with data:', {
      species: pet.species,
      birthDate: pet.birthDate,
      ageWeeks: pet.ageWeeks,
      ageMonths: pet.ageMonths,
      ageYears: pet.ageYears
    })
    
    // Generate vaccination appointment suggestions
    const appointmentSuggestions = generateVaccinationAppointments(pet, existingVaccinations)
    console.log('📅 Generated appointment suggestions:', appointmentSuggestions.length, appointmentSuggestions)
    
    if (appointmentSuggestions.length === 0) {
      console.log(`No vaccination appointments needed for ${pet.name}`)
      return []
    }
    
    // Find available vaccination services
    const availableServices = await findVaccinationServices()
    console.log('🔍 Found available vaccination services:', availableServices.length, availableServices.map(s => s.name))
    
    // Create appointment suggestions with service mapping
    const scheduledAppointments = []
    
    for (const suggestion of appointmentSuggestions) {
      // Find matching service
      const matchingService = findMatchingService(suggestion.serviceName, availableServices)
      console.log(`🔍 Looking for service matching "${suggestion.serviceName}":`, matchingService ? matchingService.name : 'No match')
      
      if (matchingService) {
        const appointmentData = {
          id: `vacc_suggest_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`,
          type: 'vaccination_suggestion',
          status: 'suggestion',
          petId: pet.id,
          petName: pet.name,
          serviceId: matchingService.id,
          serviceName: matchingService.name,
          suggestedDate: suggestion.suggestedDate,
          priority: suggestion.priority,
          series: suggestion.series,
          dose: suggestion.dose,
          totalDoses: suggestion.totalDoses,
          isCore: suggestion.isCore,
          description: suggestion.description,
          estimatedDuration: suggestion.estimatedDuration,
          notes: suggestion.notes,
          createdAt: new Date(),
          updatedAt: new Date(),
          isAutoGenerated: true,
          source: 'vaccination_series'
        }
        
        // Save to Firestore
        await saveVaccinationSuggestion(appointmentData)
        scheduledAppointments.push(appointmentData)
        
        console.log(`✅ Created vaccination suggestion for ${pet.name}: ${suggestion.serviceName}`)
      } else {
        console.log(`❌ No matching service found for ${suggestion.serviceName}`)
      }
    }
    
    console.log(`🎯 Auto-scheduling completed for ${pet.name}: ${scheduledAppointments.length} suggestions created`)
    return scheduledAppointments
  } catch (error) {
    console.error('Error auto-scheduling vaccinations:', error)
    throw new Error('Failed to auto-schedule vaccinations')
  }
}

/**
 * Find vaccination service by name
 * @param {string} vaccineName - Name of the vaccine
 * @returns {Promise<Object|null>} Vaccination service or null
 */
async function findVaccinationServiceByName(vaccineName) {
  try {
    const servicesRef = collection(db, 'services')
    const q = query(
      servicesRef,
      where('isVaccination', '==', true),
      where('archived', '==', false)
    )
    
    const snapshot = await getDocs(q)
    const services = snapshot.docs.map(doc => ({ id: doc.id, ...doc.data() }))
    
    console.log('🔍 Found vaccination services:', services.map(s => ({
      id: s.id,
      name: s.name,
      vaccineType: s.vaccineType,
      isVaccination: s.isVaccination
    })))
    
    // First try exact match
    let matchingService = services.find(service => 
      service.name.toLowerCase() === vaccineName.toLowerCase()
    )
    
    if (matchingService) {
      console.log('✅ Exact match found:', matchingService.name)
      return matchingService
    }
    
    // Try partial match by name
    matchingService = services.find(service => 
      service.name.toLowerCase().includes(vaccineName.toLowerCase()) ||
      vaccineName.toLowerCase().includes(service.name.toLowerCase())
    )
    
    if (matchingService) {
      console.log('✅ Partial name match found:', matchingService.name)
      return matchingService
    }
    
    // Try matching by vaccineType
    matchingService = services.find(service => 
      service.vaccineType && 
      service.vaccineType.toLowerCase() === vaccineName.toLowerCase()
    )
    
    if (matchingService) {
      console.log('✅ VaccineType match found:', matchingService.name)
      return matchingService
    }
    
    // Try partial match by vaccineType
    matchingService = services.find(service => 
      service.vaccineType && 
      (service.vaccineType.toLowerCase().includes(vaccineName.toLowerCase()) ||
       vaccineName.toLowerCase().includes(service.vaccineType.toLowerCase()))
    )
    
    if (matchingService) {
      console.log('✅ Partial vaccineType match found:', matchingService.name)
      return matchingService
    }
    
    console.log('❌ No matching vaccination service found for:', vaccineName)
    return null
  } catch (error) {
    console.error('Error finding vaccination service by name:', error)
    return null
  }
}

