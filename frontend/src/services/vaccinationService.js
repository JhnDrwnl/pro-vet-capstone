/**
 * Fetch service details by service IDs
 * @param {Array} serviceIds - Array of service IDs
 * @returns {Promise<Array>} Array of service objects
 */
export async function fetchServiceDetails(serviceIds) {
  try {
    if (!serviceIds || serviceIds.length === 0) {
      return []
    }

    const servicesRef = collection(db, 'services')
    const serviceDetails = []

    for (const serviceId of serviceIds) {
      try {
        const serviceDoc = await getDoc(doc(db, 'services', serviceId))
        if (serviceDoc.exists()) {
          const serviceData = serviceDoc.data()
          serviceDetails.push({
            id: serviceDoc.id,
            ...serviceData
          })
        }
      } catch (error) {
        console.error(`Error fetching service ${serviceId}:`, error)
      }
    }

    return serviceDetails
  } catch (error) {
    console.error('Error fetching service details:', error)
    return []
  }
}

/**
 * Merge appointment-based and manual vaccination records
 * @param {Array} appointmentVaccinations - Vaccinations from appointments
 * @param {Array} manualVaccinations - Manually added vaccinations
 * @returns {Array} Merged and deduplicated vaccination records
 */
export function mergeVaccinationRecords(appointmentVaccinations, manualVaccinations) {
  const allVaccinations = [...(appointmentVaccinations || []), ...(manualVaccinations || [])]
  
  // Remove duplicates based on appointmentId and serviceId
  const uniqueVaccinations = allVaccinations.filter((vaccination, index, self) => {
    if (vaccination.appointmentId && vaccination.serviceId) {
      return index === self.findIndex(v => 
        v.appointmentId === vaccination.appointmentId && 
        v.serviceId === vaccination.serviceId
      )
    }
    return true
  })

  // Sort by date (newest first)
  return uniqueVaccinations.sort((a, b) => new Date(b.date) - new Date(a.date))
}
