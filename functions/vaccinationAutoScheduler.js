const functions = require('firebase-functions');
const admin = require('firebase-admin');

// Initialize Firebase Admin if not already initialized
if (!admin.apps.length) {
  admin.initializeApp();
}

const db = admin.firestore();

/**
 * Cloud Function to run vaccination autoscheduling for all pets
 * This function can be triggered manually or on a schedule
 */
exports.runVaccinationAutoScheduling = functions.https.onCall(async (data, context) => {
  // Check if user is authenticated
  if (!context.auth) {
    throw new functions.https.HttpsError('unauthenticated', 'User must be authenticated');
  }

  const userId = context.auth.uid;
  
  try {
    console.log(`Starting vaccination autoscheduling for user: ${userId}`);
    
    // Get user's pets
    const petsSnapshot = await db.collection('pets')
      .where('userId', '==', userId)
      .get();
    
    if (petsSnapshot.empty) {
      console.log(`No pets found for user: ${userId}`);
      return { success: true, message: 'No pets found', suggestionsCreated: 0 };
    }
    
    const pets = petsSnapshot.docs.map(doc => ({
      id: doc.id,
      ...doc.data()
    }));
    
    let totalSuggestionsCreated = 0;
    const results = [];
    
    // Process each pet
    for (const pet of pets) {
      try {
        const petSuggestions = await processPetVaccinations(pet, userId);
        totalSuggestionsCreated += petSuggestions.length;
        
        results.push({
          petId: pet.id,
          petName: pet.name,
          suggestionsCreated: petSuggestions.length,
          success: true
        });
        
        console.log(`Processed pet ${pet.name}: ${petSuggestions.length} suggestions created`);
      } catch (error) {
        console.error(`Error processing pet ${pet.name}:`, error);
        results.push({
          petId: pet.id,
          petName: pet.name,
          suggestionsCreated: 0,
          success: false,
          error: error.message
        });
      }
    }
    
    console.log(`Vaccination autoscheduling completed for user ${userId}. Total suggestions: ${totalSuggestionsCreated}`);
    
    return {
      success: true,
      message: 'Vaccination autoscheduling completed',
      suggestionsCreated: totalSuggestionsCreated,
      results: results
    };
    
  } catch (error) {
    console.error('Error in vaccination autoscheduling:', error);
    throw new functions.https.HttpsError('internal', 'Failed to run vaccination autoscheduling');
  }
});

/**
 * Process vaccinations for a single pet
 * @param {Object} pet - Pet object
 * @param {string} userId - User ID
 * @returns {Promise<Array>} Array of created suggestions
 */
async function processPetVaccinations(pet, userId) {
  // Get pet's existing vaccinations
  const existingVaccinations = pet.vaccinations || [];
  
  // Get vaccination series template for this pet
  const series = getVaccinationSeriesForPet(pet);
  if (!series) {
    console.log(`No vaccination series found for pet ${pet.name} (${pet.species})`);
    return [];
  }
  
  // Calculate upcoming vaccinations
  const upcomingVaccinations = calculateUpcomingVaccinations(pet, series, existingVaccinations);
  
  if (upcomingVaccinations.length === 0) {
    console.log(`No upcoming vaccinations needed for pet ${pet.name}`);
    return [];
  }
  
  // Get available vaccination services
  const availableServices = await getVaccinationServices();
  
  // Create vaccination suggestions
  const suggestions = [];
  
  for (const vaccination of upcomingVaccinations) {
    try {
      // Find matching service
      const matchingService = findMatchingService(vaccination.name, availableServices);
      
      if (matchingService) {
        const suggestion = {
          id: `vacc_suggest_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`,
          type: 'vaccination_suggestion',
          status: 'suggestion',
          petId: pet.id,
          petName: pet.name,
          serviceId: matchingService.id,
          serviceName: matchingService.name,
          suggestedDate: vaccination.dueDate,
          priority: vaccination.priority,
          series: vaccination.series,
          dose: vaccination.dose,
          totalDoses: vaccination.totalDoses,
          isCore: vaccination.isCore,
          description: vaccination.description,
          estimatedDuration: 30,
          notes: `Automatic vaccination appointment for ${vaccination.name} - ${vaccination.description}`,
          createdAt: admin.firestore.FieldValue.serverTimestamp(),
          updatedAt: admin.firestore.FieldValue.serverTimestamp(),
          isAutoGenerated: true,
          source: 'vaccination_series',
          userId: userId
        };
        
        // Save to Firestore
        await db.collection('vaccinationSuggestions').doc(suggestion.id).set(suggestion);
        suggestions.push(suggestion);
        
        console.log(`Created vaccination suggestion for ${pet.name}: ${vaccination.name}`);
      }
    } catch (error) {
      console.error(`Error creating suggestion for ${vaccination.name}:`, error);
    }
  }
  
  return suggestions;
}

/**
 * Get vaccination series template for a pet
 * @param {Object} pet - Pet object
 * @returns {Object|null} Vaccination series template
 */
function getVaccinationSeriesForPet(pet) {
  if (!pet.species || !pet.birthDate) {
    return null;
  }
  
  const species = pet.species.toLowerCase();
  const ageWeeks = calculateAgeInWeeks(pet.birthDate.toDate());
  const ageMonths = calculateAgeInMonths(pet.birthDate.toDate());
  
  if (species.includes('dog') || species.includes('puppy')) {
    if (ageWeeks <= 16) {
      return VACCINATION_SERIES_TEMPLATES.puppy;
    } else {
      return VACCINATION_SERIES_TEMPLATES.adultDog;
    }
  } else if (species.includes('cat') || species.includes('kitten')) {
    if (ageWeeks <= 16) {
      return VACCINATION_SERIES_TEMPLATES.kitten;
    } else {
      return VACCINATION_SERIES_TEMPLATES.adultCat;
    }
  }
  
  return null;
}

/**
 * Calculate pet's age in weeks
 * @param {Date} birthDate - Pet's birth date
 * @returns {number} Age in weeks
 */
function calculateAgeInWeeks(birthDate) {
  if (!birthDate) return 0;
  
  const birth = new Date(birthDate);
  const now = new Date();
  const diffTime = Math.abs(now - birth);
  const diffWeeks = Math.ceil(diffTime / (1000 * 60 * 60 * 24 * 7));
  
  return diffWeeks;
}

/**
 * Calculate pet's age in months
 * @param {Date} birthDate - Pet's birth date
 * @returns {number} Age in months
 */
function calculateAgeInMonths(birthDate) {
  if (!birthDate) return 0;
  
  const birth = new Date(birthDate);
  const now = new Date();
  const diffTime = Math.abs(now - birth);
  const diffMonths = Math.ceil(diffTime / (1000 * 60 * 60 * 24 * 30.44));
  
  return diffMonths;
}

/**
 * Calculate upcoming vaccinations for a pet
 * @param {Object} pet - Pet object
 * @param {Object} series - Vaccination series template
 * @param {Array} existingVaccinations - Array of existing vaccination records
 * @returns {Array} Array of upcoming vaccinations
 */
function calculateUpcomingVaccinations(pet, series, existingVaccinations) {
  const upcomingVaccinations = [];
  const now = new Date();
  
  // Handle puppy/kitten series
  if (series.vaccines[0].ageWeeks) {
    const ageWeeks = calculateAgeInWeeks(pet.birthDate.toDate());
    
    series.vaccines.forEach(vaccine => {
      if (ageWeeks >= vaccine.ageWeeks) {
        // Check if this vaccine has been given
        const existingVaccine = existingVaccinations.find(v => 
          v.name.toLowerCase().includes(vaccine.name.toLowerCase().split(' ')[0])
        );
        
        if (!existingVaccine) {
          // First dose
          upcomingVaccinations.push({
            name: vaccine.name,
            description: vaccine.description,
            isCore: vaccine.isCore,
            dueDate: new Date(pet.birthDate.toDate().getTime() + (vaccine.ageWeeks * 7 * 24 * 60 * 60 * 1000)),
            dose: 1,
            totalDoses: vaccine.doses,
            series: series.name,
            priority: 'high'
          });
        } else if (existingVaccine.dose < vaccine.doses) {
          // Subsequent doses
          const lastDoseDate = new Date(existingVaccine.date);
          const nextDoseDate = new Date(lastDoseDate.getTime() + (vaccine.intervalWeeks * 7 * 24 * 60 * 60 * 1000));
          
          if (nextDoseDate > now) {
            upcomingVaccinations.push({
              name: vaccine.name,
              description: vaccine.description,
              isCore: vaccine.isCore,
              dueDate: nextDoseDate,
              dose: existingVaccine.dose + 1,
              totalDoses: vaccine.doses,
              series: series.name,
              priority: 'medium'
            });
          }
        }
      }
    });
  } else {
    // Handle adult boosters
    series.vaccines.forEach(vaccine => {
      const lastVaccine = existingVaccinations.find(v => 
        v.name.toLowerCase().includes(vaccine.name.toLowerCase().split(' ')[0])
      );
      
      if (lastVaccine) {
        const lastDoseDate = new Date(lastVaccine.date);
        let nextDueDate;
        
        if (vaccine.nextDueCalculation === 'months') {
          nextDueDate = new Date(lastDoseDate.getTime() + (vaccine.nextDueValue * 30.44 * 24 * 60 * 60 * 1000));
        } else if (vaccine.nextDueCalculation === 'weeks') {
          nextDueDate = new Date(lastDoseDate.getTime() + (vaccine.nextDueValue * 7 * 24 * 60 * 60 * 1000));
        }
        
        if (nextDueDate > now) {
          upcomingVaccinations.push({
            name: vaccine.name,
            description: vaccine.description,
            isCore: vaccine.isCore,
            dueDate: nextDueDate,
            dose: 'booster',
            totalDoses: 1,
            series: series.name,
            priority: 'medium'
          });
        }
      } else {
        // First time vaccine for adult pet
        upcomingVaccinations.push({
          name: vaccine.name,
          description: vaccine.description,
          isCore: vaccine.isCore,
          dueDate: now,
          dose: 1,
          totalDoses: 1,
          series: series.name,
          priority: 'high'
        });
      }
    });
  }
  
  // Sort by due date and priority
  return upcomingVaccinations.sort((a, b) => {
    if (a.priority === 'high' && b.priority !== 'high') return -1;
    if (b.priority === 'high' && a.priority !== 'high') return 1;
    return new Date(a.dueDate) - new Date(b.dueDate);
  });
}

/**
 * Get available vaccination services
 * @returns {Promise<Array>} Array of vaccination services
 */
async function getVaccinationServices() {
  try {
    const servicesSnapshot = await db.collection('services')
      .where('isVaccination', '==', true)
      .where('archived', '==', false)
      .get();
    
    return servicesSnapshot.docs.map(doc => ({
      id: doc.id,
      ...doc.data()
    }));
  } catch (error) {
    console.error('Error getting vaccination services:', error);
    return [];
  }
}

/**
 * Find matching service for a vaccination
 * @param {string} vaccineName - Name of the vaccine
 * @param {Array} availableServices - Array of available services
 * @returns {Object|null} Matching service
 */
function findMatchingService(vaccineName, availableServices) {
  if (!availableServices || availableServices.length === 0) {
    return null;
  }
  
  const vaccineNameLower = vaccineName.toLowerCase();
  
  // Try exact match first
  let exactMatch = availableServices.find(service => 
    service.name.toLowerCase() === vaccineNameLower
  );
  
  if (exactMatch) return exactMatch;
  
  // Try partial matches
  const partialMatches = availableServices.filter(service => {
    const serviceNameLower = service.name.toLowerCase();
    const keyTerms = vaccineNameLower.split(' ');
    return keyTerms.some(term => 
      term.length > 2 && serviceNameLower.includes(term)
    );
  });
  
  if (partialMatches.length > 0) {
    // Return the best partial match (prioritize core vaccines)
    return partialMatches.sort((a, b) => {
      if (a.name.toLowerCase().includes('core') && !b.name.toLowerCase().includes('core')) return -1;
      if (!a.name.toLowerCase().includes('core') && b.name.toLowerCase().includes('core')) return 1;
      return 0;
    })[0];
  }
  
  // Fallback to generic vaccination service
  return availableServices.find(service => 
    service.name.toLowerCase().includes('vaccination') ||
    service.name.toLowerCase().includes('vaccine')
  ) || availableServices[0];
}

