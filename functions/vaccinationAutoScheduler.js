/**
 * Scheduled function to run vaccination autoscheduling daily
 * This can be enabled to automatically check all pets daily
 */
exports.scheduledVaccinationAutoScheduling = functions.pubsub
  .schedule('0 6 * * *') // Run at 6 AM daily
  .timeZone('America/New_York')
  .onRun(async (context) => {
    console.log('Running scheduled vaccination autoscheduling...');
    
    try {
      // Get all users with pets
      const usersSnapshot = await db.collection('users').get();
      
      let totalSuggestionsCreated = 0;
      
      for (const userDoc of usersSnapshot.docs) {
        const userId = userDoc.id;
        
        try {
          // Check if user has pets
          const petsSnapshot = await db.collection('pets')
            .where('userId', '==', userId)
            .limit(1)
            .get();
          
          if (!petsSnapshot.empty) {
            // Run autoscheduling for this user
            const result = await processUserVaccinations(userId);
            totalSuggestionsCreated += result.suggestionsCreated;
          }
        } catch (error) {
          console.error(`Error processing user ${userId}:`, error);
        }
      }
      
      console.log(`Scheduled vaccination autoscheduling completed. Total suggestions: ${totalSuggestionsCreated}`);
      return null;
      
    } catch (error) {
      console.error('Error in scheduled vaccination autoscheduling:', error);
      return null;
    }
  });

